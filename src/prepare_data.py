"""Prepare shared CIFAR-10 cache once before research jobs begin."""
import argparse,json
from pathlib import Path
from data import cifar10

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--data-root',default=str(Path(__file__).resolve().parent.parent/'data'))
    args=ap.parse_args()
    print('Preparing CIFAR-10 in',args.data_root,flush=True)
    arrays=cifar10(args.data_root)
    print(json.dumps({k:list(v.shape) for k,v in arrays.items()},indent=2),flush=True)
    print('Checksum and shared cache ready. Motion samples are generated by parent ID.',flush=True)

if __name__=='__main__':main()
